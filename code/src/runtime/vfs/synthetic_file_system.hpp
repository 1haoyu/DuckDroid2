#pragma once

#include <cstdint>
#include <functional>
#include <memory>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

#include "runtime/vfs/dir_entry.hpp"

namespace duckemu::runtime::vfs
{

class File;

// One entry a synthetic mount answers for. Blobs carry their whole immutable
// content (every open descriptor shares it); character/stream nodes build an
// open description through `create`.
struct SyntheticNode
{
	bool directory = false;
	// Guest mode bits (S_IF* | permissions). 0 means a regular file with 0444,
	// which is what most blobs want.
	uint32_t mode = 0;
	// st_rdev for character devices (Linux dev_t encoding).
	uint64_t rdev = 0;
	std::shared_ptr<const std::vector<uint8_t> > content;
	// Non-empty for nodes whose reads/writes are not a byte array (/dev/null,
	// /dev/zero, /dev/urandom). The VFS hands the guest path and open flags
	// through, so the description knows whether it was opened for writing.
	std::function<std::unique_ptr<File>(std::string path, uint64_t flags)> create;
};

// Read-only mounts that live outside the host roots. /proc is generated by the
// existing ProcFs; this interface covers fixed namespaces (/dev, and
// /dev/__properties__). Lookup takes a normalized absolute guest path.
class SyntheticFileSystem
{
    public:
	virtual ~SyntheticFileSystem() = default;

	[[nodiscard]] virtual std::optional<SyntheticNode> lookup(
		std::string_view guest_path) const = 0;

	// Entries of a directory this mount carries. `guest_dir` is the full
	// guest path; the default (no entries) is enough for mounts that only
	// expose files.
	[[nodiscard]] virtual std::vector<DirEntry> list(std::string_view guest_dir) const
	{
		(void)guest_dir;
		return {};
	}
};

} // namespace duckemu::runtime::vfs
